// Generates TypeScript types for koncavecinema-api from its OpenAPI document and writes them to
// src/lib/api/schema.d.ts (committed, so builds and CI never need to reach the API).
//
// The API serves the document at /api/docs-json. It is open on a local API (NODE_ENV=development)
// and behind HTTP Basic Auth on staging and production (SWAGGER_USER / SWAGGER_PASSWORD on the
// API). Set the matching values below in .env.local to generate from a protected environment.
//
//   API_OPENAPI_URL      default http://localhost:3000/api/docs-json
//   API_DOCS_USER        the API's SWAGGER_USER      (only for a protected environment)
//   API_DOCS_PASSWORD    the API's SWAGGER_PASSWORD  (only for a protected environment)
//
// These are developer-machine values for this script only. They are never read by the app and
// must never be NEXT_PUBLIC_ variables.
import { writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const url = process.env.API_OPENAPI_URL ?? "http://localhost:3000/api/docs-json";
const user = process.env.API_DOCS_USER;
const password = process.env.API_DOCS_PASSWORD;
const output = "src/lib/api/schema.d.ts";

const headers = { Accept: "application/json" };
if (user && password) {
  headers.Authorization = `Basic ${Buffer.from(`${user}:${password}`).toString("base64")}`;
}

console.log(
  `Fetching the OpenAPI document from ${url}${headers.Authorization ? " (Basic Auth)" : ""}`,
);

let response;
try {
  response = await fetch(url, { headers });
} catch (error) {
  fail(`Could not reach ${url}. Is the API running? (${error.cause?.code ?? error.message})`);
}

if (response.status === 401) {
  fail(
    "The API docs are protected. Set API_DOCS_USER and API_DOCS_PASSWORD in .env.local " +
      "to that environment's SWAGGER_USER and SWAGGER_PASSWORD.",
  );
}
if (response.status === 404) {
  fail(
    "No OpenAPI document at that address. Check that the Koncave API (not another app) is the " +
      "one on that port, and that SWAGGER_ENABLED=true on it.",
  );
}
if (!response.ok) fail(`The API answered ${response.status} ${response.statusText}.`);

const document = await response.json();
const ast = await openapiTS(document);
const header =
  "// Generated by `npm run api:types` from the koncavecinema-api OpenAPI document.\n" +
  "// Do not edit by hand; regenerate after the API changes.\n\n";

await writeFile(output, header + astToString(ast));
console.log(`Wrote ${output}`);

function fail(message) {
  console.error(`api:types failed: ${message}`);
  process.exit(1);
}
